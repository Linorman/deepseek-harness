import { expect, it, vi } from 'vitest'
import { NotificationQueue } from '../src/notification-queue.ts'

const packet = (publish: () => Promise<void>, text = '中文') => ({ method: 'session.event', params: { text }, publish })
const size = (text = '中文') => Buffer.byteLength(JSON.stringify({ jsonrpc: '2.0', method: 'session.event', params: { text } }) + '\n')

it('serializes publishers and accounts for an active frame until transport drain completes', async () => {
  const held = Promise.withResolvers<undefined>()
  const first = vi.fn(async () => { await held.promise })
  const second = vi.fn(async () => {})
  const failure = vi.fn()
  const queue = new NotificationQueue({ frames: 2, bytes: 2 * size() }, failure)
  queue.push(packet(first))
  queue.push(packet(second))
  expect(first).toHaveBeenCalledOnce()
  expect(second).not.toHaveBeenCalled()
  held.resolve(undefined)
  await queue.drain()
  expect(second).toHaveBeenCalledOnce()
  expect(failure).not.toHaveBeenCalled()
  queue.push(packet(second))
  await queue.drain()
  expect(second).toHaveBeenCalledTimes(2)
})

it.each(['frames', 'bytes'] as const)('stops the entire backlog when its %s allowance is exceeded during authorization', async (allowance) => {
  const held = Promise.withResolvers<undefined>()
  const later = vi.fn(async () => {})
  const failure = vi.fn()
  const queue = new NotificationQueue({ frames: allowance === 'frames' ? 1 : 4, bytes: allowance === 'bytes' ? size() : 4 * size() }, failure)
  queue.push(packet(async () => { await held.promise }))
  queue.push(packet(later))
  queue.push(packet(later))
  held.resolve(undefined)
  await queue.drain()
  expect(later).not.toHaveBeenCalled()
  expect(failure).toHaveBeenCalledExactlyOnceWith(expect.objectContaining({ message: 'SDK notification backlog exceeded its configured allowance' }))
})

it('includes the JSON-RPC envelope, newline and UTF-8 bytes at the exact single-frame allowance', async () => {
  const publish = vi.fn(async () => {})
  const failure = vi.fn()
  const exact = new NotificationQueue({ frames: 1, bytes: size() }, failure)
  exact.push(packet(publish))
  await exact.drain()
  expect(publish).toHaveBeenCalledOnce()
  const tooSmall = new NotificationQueue({ frames: 1, bytes: size() - 1 }, failure)
  tooSmall.push(packet(publish))
  await tooSmall.drain()
  expect(publish).toHaveBeenCalledOnce()
  expect(failure).toHaveBeenCalledOnce()
})

it('discards retired generations while draining new packets and contains old publisher failures', async () => {
  const held = Promise.withResolvers<undefined>()
  const discarded = vi.fn(async () => {})
  const current = vi.fn(async () => {})
  const failure = vi.fn()
  const queue = new NotificationQueue({ frames: 3, bytes: 3 * size() }, failure)
  queue.push(packet(async () => { await held.promise; throw new Error('old provider detail') }))
  queue.push(packet(discarded))
  queue.reset()
  queue.push(packet(current))
  held.resolve(undefined)
  await queue.drain()
  expect(current).toHaveBeenCalledOnce()
  expect(discarded).not.toHaveBeenCalled()
  expect(failure).not.toHaveBeenCalled()
})

it('contains publication and transport-owner failures without leaking provider diagnostics', async () => {
  const failure = vi.fn(() => { throw new Error('owner callback failed') })
  const queue = new NotificationQueue({ frames: 1, bytes: size() }, failure)
  queue.push(packet(async () => { throw new Error('private provider detail') }))
  await queue.drain()
  expect(failure).toHaveBeenCalledExactlyOnceWith(expect.objectContaining({ message: 'SDK notification publication failed' }))
  queue.reset()
  expect(() => { queue.push(packet(async () => {}, 'x'.repeat(size()))) }).not.toThrow()
  await queue.drain()
  expect(failure).toHaveBeenCalledTimes(2)
})

it('drains a packet admitted between publisher completion and queue release', async () => {
  const first = vi.fn(async () => {})
  const second = vi.fn(async () => {})
  const queue = new NotificationQueue({ frames: 2, bytes: 2 * size() }, vi.fn())
  queue.push(packet(first))
  await Promise.resolve()
  queue.push(packet(second))
  await queue.drain()
  expect(second).toHaveBeenCalledOnce()
})

it.each([{ frames: 0, bytes: 1 }, { frames: 1.5, bytes: 1 }, { frames: 1, bytes: 0 }, { frames: 1, bytes: Infinity }])('rejects invalid allowances %j', (limits) => {
  expect(() => new NotificationQueue(limits, vi.fn())).toThrow('positive safe integers')
})
